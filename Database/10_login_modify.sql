-- 3. Create the logins
INSERT INTO PATIENT_AUTH (patient_id, email, password_hash, created_at)
SELECT p.patient_id, p.email, pw.password_hash, p.registered_at
FROM (
    SELECT pt.patient_id,
           LOWER(CONCAT(
               pt.first_name, '.', pt.last_name,
               IF(ROW_NUMBER() OVER w > 1, ROW_NUMBER() OVER w, ''),
               '@example.com'
           )) AS email,
           LEAST(
               COALESCE(
                   (SELECT MIN(TIMESTAMP(a.appointment_date, a.scheduled_end))
                    FROM APPOINTMENT a
                    WHERE a.patient_id = pt.patient_id),
                   '2025-09-01 09:00:00'),
               '2026-09-27 18:00:00'
           ) AS registered_at
    FROM PATIENT pt
    WINDOW w AS (PARTITION BY pt.first_name, pt.last_name ORDER BY pt.patient_id)
) p
JOIN tmp_patient_password pw ON pw.patient_id = p.patient_id
WHERE NOT EXISTS (
    SELECT 1 FROM PATIENT_AUTH existing
    WHERE existing.patient_id = p.patient_id
       OR existing.email = p.email
);

DROP TEMPORARY TABLE tmp_patient_password;

